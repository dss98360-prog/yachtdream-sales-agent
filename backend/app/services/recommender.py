def recommend_program(data: QualificationRequest) -> Recommendation:
    if data.goal in {"cruise", "family"}:
        program = PROGRAMS["cruise"]
        reason = "Вы выбрали морской отдых и мягкое знакомство с яхтингом. Учебный круиз позволит попробовать жизнь на яхте без необходимости сразу брать на себя роль капитана."
    elif data.experience == "experienced" or data.goal == "skills":
        program = PROGRAMS["advanced"]
        reason = "У вас уже есть опыт, поэтому базовая программа может оказаться слишком простой. Продвинутый формат поможет систематизировать навыки и перейти к более сложным капитанским задачам."
    elif data.goal == "captain" and data.experience == "beginner":
        program = PROGRAMS["intensive"]
        reason = "Вы хотите стать капитаном и уже знакомы с яхтингом. Интенсивный формат объединяет предварительную онлайн-теорию и концентрированную морскую практику."
    elif data.goal == "captain":
        program = PROGRAMS["bareboat"]
        reason = "Ваша цель — самостоятельное управление яхтой. Полная программа Bareboat Skipper последовательно проведёт от теории и безопасности к навигации, швартовкам и первому чартеру."
    else:
        program = PROGRAMS["crew"]
        reason = "Для первого знакомства лучше начать с роли компетентного члена экипажа: освоить безопасность, устройство яхты и основные действия на борту."

    location_note = {
        "turkey": "Предпочтение Турции соответствует основной базе морской практики в Мармарисе.",
        "thailand": "Интерес к Таиланду учтён; актуальные программы и даты необходимо подтвердить у администратора.",
        "any": "Администратор поможет выбрать подходящую акваторию с учётом сезона.",
    }[data.destination]

    return Recommendation(
        program_id=program.id,
        title=program.title,
        subtitle=program.subtitle,
        reason=f"{reason} {location_note}",
        benefits=list(program.benefits),
        next_step="Оставьте заявку — демонстрационный администратор уточнит даты, состав группы и актуальные условия.",
    )


